/// A webview cannot end another webview's subscription nor answer an ack offered to another.
#[test]
fn webviews_are_isolated() {
    let mut h = Harness::new();
    let other = h.window("other");
    h.connect("iso", conformance(), 1);
    let theirs = subscribe_on(&other, "iso", None, 50)["subscription"]
        .as_u64()
        .unwrap();
    let mine = h.subscribe("iso", Some(&["question"]), 2);
    assert_eq!(
        invoke_on(
            &other,
            "unsubscribe",
            json!({ "id": "iso", "subscription": mine })
        )
        .unwrap(),
        json!(false)
    );
    h.ok(
        "emit",
        json!({ "id": "iso", "event": "ask", "args": { "args": [] } }),
    );
    let q1 = h.event(1, "question");
    let q2 = h.event(2, "question");
    let q50 = h.event(50, "question");
    // finding 8: one server ack, one ack id everywhere
    assert_eq!(q1["ackId"], q2["ackId"]);
    assert_eq!(q1["ackId"], q50["ackId"]);
    // an app with a second window: both were offered it, so the first answer wins
    let ack = json!({ "id": "iso", "ackId": q1["ackId"], "args": { "args": ["mine"] } });
    h.ok("ack", ack.clone());
    assert_eq!(
        kind(invoke_on(&other, "ack", ack.clone()).unwrap_err()),
        "UnknownAck"
    );
    assert_eq!(h.err_kind("ack", ack), "UnknownAck", "answered once");
    // an ack offered only to `main` (other unsubscribed) is not answerable from `other`
    assert_eq!(
        invoke_on(
            &other,
            "unsubscribe",
            json!({ "id": "iso", "subscription": theirs })
        )
        .unwrap(),
        json!(true)
    );
    h.ok(
        "emit",
        json!({ "id": "iso", "event": "ask", "args": { "args": [] } }),
    );
    let q = h.wait(1, |m| m["event"] == "question" && m["ackId"] != q1["ackId"]);
    let ack = json!({ "id": "iso", "ackId": q["ackId"], "args": { "args": [] } });
    assert_eq!(
        kind(invoke_on(&other, "ack", ack.clone()).unwrap_err()),
        "UnknownAck"
    );
    h.ok("ack", ack);
    h.ok("disconnect", json!({ "id": "iso" }));
}

