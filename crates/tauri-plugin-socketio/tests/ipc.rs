#[test]
fn connect_rejected_carries_the_server_data() {
    let mut h = Harness::new();
    let err = h
        .invoke(
            "connect",
            json!({
                "id": "rej",
                "options": { "url": socket_io_server(), "namespace": "/reject", "query": { "token": "s3cr3t" } },
                "channel": "__CHANNEL__:1",
            }),
        )
        .expect_err("rejected");
    assert_eq!(err["kind"], "ConnectRejected");
    assert_eq!(err["data"], json!({ "reason": "test" }));
    let text = err.to_string();
    assert!(
        !text.contains("s3cr3t") && !text.contains("localhost"),
        "{text}"
    );
    // nothing was registered; before the rejection the channel may only have seen the
    // attempt's states (`connecting`, `closed`), never `connected` or an event
    assert_eq!(h.ok("list", json!({})), json!([]));
    let seen = h.drain(1, Duration::from_millis(300));
    assert!(
        seen.iter().all(|m| m["type"] == "state"
            && ["connecting", "closed"].contains(&m["state"]["status"].as_str().unwrap())),
        "{seen:?}"
    );
}

