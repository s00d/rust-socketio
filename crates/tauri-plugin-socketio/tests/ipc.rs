const ALL: &[&str] = &[
    "connect",
    "disconnect",
    "emit",
    "emit_with_ack",
    "ack",
    "subscribe",
    "unsubscribe",
    "list",
    "state",
    "link_info",
    "set_auth",
    "set_headers",
    "set_query",
    "reconnect",
];
/// The commands the `allow-read` set should grant.
const READ: &[&str] = &["list", "subscribe", "unsubscribe", "state", "link_info"];

const WAIT: Duration = Duration::from_secs(10);

/// The runtime ACL an app gets from a capability with `permissions`, resolved from the
/// plugin's permission files the way tauri-build does.
fn authority(permissions: &[&str]) -> RuntimeAuthority {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("permissions");
    let mut paths = vec![dir.join("default.toml")];
    for entry in std::fs::read_dir(dir.join("autogenerated/commands")).unwrap() {
        paths.push(entry.unwrap().path());
    }
    let files: Vec<PermissionFile> = paths
        .iter()
        .map(|p| toml::from_str(&std::fs::read_to_string(p).unwrap()).unwrap())
        .collect();
    let acl = BTreeMap::from([("socketio".to_owned(), Manifest::new(files, None))]);
    let capability: Capability = serde_json::from_value(json!({
        "identifier": "test",
        "windows": ["*"],
        "permissions": permissions,
    }))
    .unwrap();
    let resolved = Resolved::resolve(
        &acl,
        BTreeMap::from([("test".to_owned(), capability)]),
        Target::current(),
    )
    .expect("the capability resolves against the plugin's permissions");
    RuntimeAuthority::new(acl, resolved)
}

struct Harness {
    app: App<MockRuntime>,
    webview: WebviewWindow<MockRuntime>,
    messages: mpsc::Receiver<(u32, Value)>,
    /// Messages read while looking for another one.
    seen: VecDeque<(u32, Value)>,
}

impl Harness {
    /// A mock app with the plugin and `socketio:default`.
    fn new() -> Harness {
        Harness::with(&["socketio:default"], tauri_plugin_socketio::Builder::new())
    }

    /// A mock app whose windows have a capability with `permissions`.
    fn with(permissions: &[&str], plugin: tauri_plugin_socketio::Builder) -> Harness {
        let (tx, messages) = mpsc::channel();
        let mut context = mock_context(noop_assets());
        *context.runtime_authority_mut() = authority(permissions);
        let app = mock_builder()
            .plugin(plugin.build())
            .channel_interceptor(move |_, callback, _, body| {
                if let InvokeResponseBody::Json(json) = body {
                    let _ = tx.send((callback.0, serde_json::from_str(json).unwrap()));
                }
                true
            })
            .build(context)
            .expect("mock app");
        let webview = WebviewWindowBuilder::new(&app, "main", Default::default())
            .build()
            .expect("webview");
        Harness {
            app,
            webview,
            messages,
            seen: VecDeque::new(),
        }
    }

    /// Another webview window of the same app.
    fn window(&self, label: &str) -> WebviewWindow<MockRuntime> {
        WebviewWindowBuilder::new(&self.app, label, Default::default())
            .build()
            .expect("webview")
    }

    fn invoke(&self, cmd: &str, body: Value) -> Result<Value, Value> {
        invoke_on(&self.webview, cmd, body)
    }

    fn ok(&self, cmd: &str, body: Value) -> Value {
        self.invoke(cmd, body)
            .unwrap_or_else(|e| panic!("{cmd} failed: {e}"))
    }

    /// The `kind` of the error `cmd` fails with.
    fn err_kind(&self, cmd: &str, body: Value) -> String {
        kind(self.invoke(cmd, body).expect_err(cmd))
    }

    /// The next message on `channel` that matches `pred`; earlier ones are skipped.
    fn wait(&mut self, channel: u32, pred: impl Fn(&Value) -> bool) -> Value {
        let deadline = Instant::now() + WAIT;
        if let Some(pos) = self.seen.iter().position(|(c, m)| *c == channel && pred(m)) {
            let found = self.seen.remove(pos).unwrap().1;
            self.seen.retain(|(c, _)| *c != channel);
            return found;
        }
        self.seen.retain(|(c, _)| *c != channel);
        loop {
            let left = deadline.saturating_duration_since(Instant::now());
            let (c, m) = self
                .messages
                .recv_timeout(left)
                .unwrap_or_else(|_| panic!("no matching message on channel {channel}"));
            if c == channel && pred(&m) {
                return m;
            }
            if c != channel {
                self.seen.push_back((c, m));
            }
        }
    }

    fn event(&mut self, channel: u32, name: &str) -> Value {
        self.wait(channel, |m| m["type"] == "event" && m["event"] == name)
    }

    fn state(&mut self, channel: u32, status: &str) -> Value {
        self.wait(channel, |m| {
            m["type"] == "state" && m["state"]["status"] == status
        })["state"]
            .clone()
    }

    /// Every message of `channel` that arrives within `quiet`.
    fn drain(&mut self, channel: u32, quiet: Duration) -> Vec<Value> {
        let mut out: Vec<Value> = self
            .seen
            .iter()
            .filter(|(c, _)| *c == channel)
            .map(|(_, m)| m.clone())
            .collect();
        self.seen.retain(|(c, _)| *c != channel);
        while let Ok((c, m)) = self.messages.recv_timeout(quiet) {
            if c == channel {
                out.push(m);
            } else {
                self.seen.push_back((c, m));
            }
        }
        out
    }

    /// `connect` from the webview with channel `channel`: it resolves connected, and the
    /// channel's first state message is that snapshot. Returns the subscription id.
    fn connect(&mut self, id: &str, options: Value, channel: u32) -> u64 {
        let res = self.ok(
            "connect",
            json!({ "id": id, "options": options, "channel": format!("__CHANNEL__:{channel}") }),
        );
        assert_eq!(res["state"]["status"], "connected", "{res}");
        let snapshot = self.wait(channel, |m| m["type"] == "state" && m["snapshot"] == true);
        assert_eq!(snapshot["state"], res["state"]);
        res["subscription"].as_u64().unwrap()
    }

    fn subscribe(&mut self, id: &str, events: Option<&[&str]>, channel: u32) -> u64 {
        subscribe_on(&self.webview, id, events, channel)["subscription"]
            .as_u64()
            .unwrap()
    }
}

fn invoke_on(webview: &WebviewWindow<MockRuntime>, cmd: &str, body: Value) -> Result<Value, Value> {
    let request = InvokeRequest {
        cmd: format!("plugin:socketio|{cmd}"),
        callback: CallbackFn(0),
        error: CallbackFn(1),
        url: if cfg!(any(windows, target_os = "android")) {
            "http://tauri.localhost"
        } else {
            "tauri://localhost"
        }
        .parse()
        .unwrap(),
        body: InvokeBody::Json(body),
        headers: Default::default(),
        invoke_key: INVOKE_KEY.to_string(),
    };
    get_ipc_response(webview, request).map(|b| b.deserialize::<Value>().unwrap())
}

fn subscribe_on(
    webview: &WebviewWindow<MockRuntime>,
    id: &str,
    events: Option<&[&str]>,
    channel: u32,
) -> Value {
    invoke_on(
        webview,
        "subscribe",
        json!({ "id": id, "events": events, "channel": format!("__CHANNEL__:{channel}") }),
    )
    .unwrap_or_else(|e| panic!("subscribe: {e}"))
}

fn kind(err: Value) -> String {
    err["kind"]
        .as_str()
        .unwrap_or_else(|| panic!("not a plugin error: {err}"))
        .to_owned()
}

fn conformance() -> Value {
    json!({ "url": conformance_server() })
}

/// An ACL refusal is a plain string from tauri, not a plugin error object.
fn acl_refused(result: Result<Value, Value>) -> bool {
    matches!(result, Err(Value::String(e)) if e.contains("not allowed"))
}

#[test]
fn allow_read_grants_exactly_the_observing_commands() {
    let h = Harness::with(
        &["socketio:allow-read"],
        tauri_plugin_socketio::Builder::new(),
    );
    for cmd in ALL {
        let result = h.invoke(cmd, json!({ "id": "nope" }));
        assert_eq!(
            !acl_refused(result.clone()),
            READ.contains(cmd),
            "{cmd}: {result:?}"
        );
    }
}

/// `default` reaches every command, and every command is registered with the handler (an
/// unregistered one would answer "not found", not a plugin error).
#[test]
fn default_grants_every_command_and_each_is_registered() {
    let h = Harness::new();
    for cmd in ALL {
        let result = h.invoke(cmd, json!({ "id": "nope" }));
        assert!(!acl_refused(result.clone()), "{cmd}: {result:?}");
        if let Err(Value::String(e)) = &result {
            assert!(!e.contains("not found"), "{cmd}: {e}");
        }
    }
    let build = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/build.rs")).unwrap();
    for cmd in ALL {
        assert!(
            build.contains(&format!("\"{cmd}\"")),
            "build.rs COMMANDS lacks {cmd}"
        );
    }
}

